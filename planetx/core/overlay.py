"""Наложение поверх подложки: какую картинку взять для тайла.

Картинки наложения рисует QGIS, по одной на тайл Web Mercator. Пока
картинка тайла не готова, берётся часть картинки ближайшего готового
предка. Так линии не пропадают при приближении, а становятся резче,
когда приходит своя картинка.

Координаты текстуры тайла u и v идут от 0 до 1, v = 0 - северный край,
как у подложки. У предка той же точке отвечают координаты
offset + scale · (u, v).
"""

import math

# Половина длины экватора Web Mercator, EPSG:3857, метры.
HALF_WORLD = 6378137.0 * math.pi

# Глубже этого количества уровней часть картинки предка размыта сильнее,
# чем помогает. Тайл тогда рисуется без наложения. Значок точечного
# слоя проекта в части картинки предка растёт в 2^n раз. При запасе
# в 6 уровней скважины у Соликамска стали кругами в 64 раза больше,
# 26 сентября 2026 года.
MAX_ANCESTOR_DEPTH = 2


def mercator_bounds(z, x, y):
    """Границы тайла в EPSG:3857: запад, юг, восток, север, метры."""
    size = 2.0 * HALF_WORLD / (1 << z)
    return (-HALF_WORLD + x * size, HALF_WORLD - (y + 1) * size,
            -HALF_WORLD + (x + 1) * size, HALF_WORLD - y * size)


def urgency(key, found):
    """Приоритет отрисовки наложения для нарисованного тайла.

    found - то, что вернула window. Тайл совсем без наложения идёт
    первым, дальше тайлы с более далёким предком, то есть с более
    размытой частью картинки.
    """
    if found is None:
        return float(MAX_ANCESTOR_DEPTH + 1)
    return float(key[0] - found[0][0])


def window(key, ready, max_depth=MAX_ANCESTOR_DEPTH):
    """Ключ картинки и (сдвиг u, сдвиг v, масштаб) или None.

    ready(key) говорит, готова ли картинка наложения тайла. Для самого
    тайла возвращается (key, (0, 0, 1)).
    """
    z, x, y = key
    for depth in range(min(z, max_depth) + 1):
        up = (z - depth, x >> depth, y >> depth)
        if ready(up):
            scale = 1.0 / (1 << depth)
            mask = (1 << depth) - 1
            return up, ((x & mask) * scale, (y & mask) * scale, scale)
    return None
