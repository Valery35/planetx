"""Каталог источников подложек и наложений модуля в data/sources.json
хранилища planetx-scene - общий файл линейки, просьба сессии rustPlanetX
по слову автора от 7 ноября 2026 года «новые данные из Про раскидай по
всем модулям». Источник правды - core/basemap.py и core/tileoverlays.py,
названия наложений - строки реестра ui/tileoverlays.py.

Запуск: export_sources.py [папка planetx-scene] [--check]. Без папки -
PLANETX_SCENE, иначе planetx-scene рядом с рабочей копией. --check
сверяет файл с каталогом модуля и не пишет.

В адресе места {z}, {x}, {y}, у Bing - {q}, quadkey. Поля источника:
key, name_ru, name_en, url, max_level, credit, terms, group, kind
(basemap или overlay), projection (webmercator или
ellipsoidal - EPSG:3395), warn (окно условий перед добавлением). У
районной карты ещё bbox [запад, юг, восток, север], from_level - уровень,
с которого берётся сама карта, и fallback - ключ подложки вне охвата.
"""
import ast
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PLUGIN = os.path.join(ROOT, "planetx")
sys.path.insert(0, os.path.join(PLUGIN, "core"))
sys.path.insert(0, PLUGIN)

import basemap  # noqa: E402
import tileoverlays  # noqa: E402
from i18n import EN  # noqa: E402

FORMAT = 1
TARGET = os.path.join("data", "sources.json")


def overlay_names():
    """Названия наложений по-русски из строк реестра ui/tileoverlays.py
    (ROW_NAMES)."""
    path = os.path.join(PLUGIN, "ui", "tileoverlays.py")
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    names = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Dict):
            continue
        for key, value in zip(node.keys, node.values):
            if isinstance(value, ast.Lambda):
                value = value.body
            if (isinstance(key, ast.Constant)
                    and key.value in tileoverlays.OVERLAYS
                    and isinstance(value, ast.Tuple) and value.elts
                    and isinstance(value.elts[0], ast.Call)
                    and value.elts[0].args
                    and isinstance(value.elts[0].args[0], ast.Constant)):
                names[key.value] = value.elts[0].args[0].value
    return names


def fallback_key(url):
    """Ключ подложки по адресу: встроенная или готовая."""
    if url == basemap.ESRI_URL:
        return "esri"
    if url == basemap.OSM_URL:
        return "osm"
    for row in basemap.READY:
        if row[3] == url:
            return row[0]
    raise KeyError(url)


def build():
    """Каталог источников словарём, порядок - порядок модуля."""
    groups = {key: group for group, keys in basemap.READY_GROUPS
              for key in keys}
    out = []
    for source in basemap.builtins():
        key = basemap.basemap_key(source)
        credit, terms = source.attribution
        out.append({"key": key, "name_ru": source.name,
                    "name_en": source.name, "url": source.url,
                    "max_level": source.max_level, "credit": credit,
                    "terms": terms, "group": "builtin", "kind": "basemap",
                    "projection": "webmercator", "warn": False})
    for key, ru, en, url, top, credit, terms, warn, scheme in basemap.READY:
        entry = {"key": key, "name_ru": ru, "name_en": en, "url": url,
                 "max_level": top, "credit": credit, "terms": terms,
                 "group": groups.get(key, ""), "kind": "basemap",
                 "projection": ("ellipsoidal" if scheme == "ellipsoidal"
                                else "webmercator"),
                 "warn": bool(warn)}
        if scheme == "regional":
            west, south, east, north, level, base = basemap.REGIONS[key]
            entry["bbox"] = [west, south, east, north]
            entry["from_level"] = level
            entry["fallback"] = fallback_key(base)
        out.append(entry)
    names = overlay_names()
    for key, overlay in tileoverlays.OVERLAYS.items():
        ru = names[key]
        out.append({"key": key, "name_ru": ru, "name_en": EN.get(ru, ru),
                    "url": overlay.url, "max_level": overlay.max_level,
                    "credit": overlay.attribution, "terms": overlay.terms,
                    "group": "tiles", "kind": "overlay",
                    "projection": "webmercator", "warn": False})
    return {"format": FORMAT,
            "about": "PlanetX base maps and tile overlays, generated by "
                     "planetx/tools/export_sources.py. URL places - {z} "
                     "{x} {y}, {q} is a Bing quadkey.",
            "sources": out}


def text():
    return json.dumps(build(), ensure_ascii=False, indent=1) + "\n"


def scene_root(argv):
    for arg in argv:
        if not arg.startswith("--"):
            return arg
    return os.environ.get("PLANETX_SCENE") or os.path.join(
        os.path.dirname(ROOT), "planetx-scene")


def main(argv):
    path = os.path.join(scene_root(argv), TARGET)
    fresh = text()
    if "--check" in argv:
        try:
            with open(path, encoding="utf-8") as fh:
                same = fh.read() == fresh
        except OSError:
            same = False
        print("совпадает" if same else "расходится: " + path)
        return 0 if same else 1
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(fresh)
    print(path, len(build()["sources"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
